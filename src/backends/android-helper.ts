// ── install (once per serial and helper version) ─────────────────────────────
const installed = new Map<string, Promise<string>>();
export function ensureHelper(serial: string): Promise<string> {
  let p = installed.get(serial);
  if (!p) {
    p = (async () => {
      const r = await adb(serial, ['shell', `[ -s ${REMOTE_DEX} ] && echo __PRESENT__`], { allowFail: true, timeoutMs: 10_000 });
      if (r.stdout.includes('__PRESENT__')) return REMOTE_DEX;
      const dir = mkdtempSync(join(tmpdir(), 'pd-helper-'));
      try {
        const f = join(dir, 'helper.dex');
        writeFileSync(f, Buffer.from(HELPER_DEX_B64, 'base64'));
        const push = await adb(serial, ['push', f, REMOTE_DEX], { allowFail: true, timeoutMs: 30_000 });
        if (push.code !== 0) throw new Error(`adb push of the helper failed: ${(push.stderr || push.stdout).trim()}`);
        await adb(serial, ['shell', `chmod 644 ${REMOTE_DEX}`], { allowFail: true, timeoutMs: 10_000 });
      } finally { rmSync(dir, { recursive: true, force: true }); }
      return REMOTE_DEX;
    })();
    const mine = p;
    mine.catch(() => { if (installed.get(serial) === mine) installed.delete(serial); });
    installed.set(serial, mine);
  }
  return p;
}
/** Forget that the helper is on the device (after a failure: the data partition may have been wiped). */
function forgetInstall(serial: string) { installed.delete(serial); }

// ── ui session protocol ─────────────────────────────────────────────────────
export interface DumpResult { xml: string; idle: boolean; sinceEventMs?: number }
/** How far an input got (core/types.ts Delivery). sent: every event was injected and handled; not_sent: nothing was
 *  injected (safe to send again); unknown: something may have reached the screen (never send it again blindly). */
export type { Delivery };
export interface InputReply { seq: number; delivery: Delivery; ms: number; detail?: string }
export type HelperReply = { ok: true; xml: string; idle: boolean; sinceEventMs?: number } | { ok: false; error: string } | { ready: true }
  | { input: InputReply };

/** Incremental parser for the helper's stdout: "PDREADY\n", "PDOK <bytes> <idle 0|1> [msSinceLastEvent]\n<bytes>",
 *  "PDERR <msg>\n", "PDIN <seq> <sent|notsent|unknown> <ms> [detail]\n".
 *  Other lines (stray output) are skipped. */
export class HelperReplyParser {
  private buf: Buffer = Buffer.alloc(0);
  push(chunk: Buffer): HelperReply[] {
    this.buf = this.buf.length ? Buffer.concat([this.buf, chunk]) : chunk;
    const out: HelperReply[] = [];
    for (;;) {
      const nl = this.buf.indexOf(10);
      if (nl < 0) break;
      const head = this.buf.subarray(0, nl).toString('utf8').replace(/\r$/, '');
      const ok = /^PDOK (\d+) ([01])(?: (\d+))?$/.exec(head);
      if (ok) {
        const n = Number(ok[1]);
        if (this.buf.length < nl + 1 + n) break;
        out.push({ ok: true, xml: this.buf.subarray(nl + 1, nl + 1 + n).toString('utf8'), idle: ok[2] === '1', ...(ok[3] ? { sinceEventMs: Number(ok[3]) } : {}) });
        this.buf = this.buf.subarray(nl + 1 + n);
        continue;
      }
      this.buf = this.buf.subarray(nl + 1);
      const inp = /^PDIN (\d+) (sent|notsent|unknown) (\d+)(?: (.*))?$/.exec(head);
      if (inp) {
        out.push({ input: { seq: Number(inp[1]), delivery: inp[2] === 'notsent' ? 'not_sent' : inp[2] as Delivery, ms: Number(inp[3]), ...(inp[4] ? { detail: inp[4] } : {}) } });
        continue;
      }
      if (head === 'PDREADY') out.push({ ready: true });
      else if (head.startsWith('PDERR ')) out.push({ ok: false, error: head.slice(6) });
    }
    return out;
  }
}

class UiSession {
  readonly child: ChildProcess;
  readonly ready: Promise<void>;
  closed = false;
  isReady = false;
  private parser = new HelperReplyParser();
  private pending: { resolve: (r: DumpResult) => void; reject: (e: Error) => void; timer: NodeJS.Timeout }[] = [];
  private inputs = new Map<number, { resolve: (r: InputReply) => void; timer: NodeJS.Timeout }>();
  private seq = 0;
  private stderr = '';
  private idleTimer: NodeJS.Timeout | undefined;
  private exited: Promise<void>;
  constructor(serial: string, dex: string) {
    this.child = spawn(adbPath(), ['-s', serial, 'shell', `CLASSPATH=${dex}:${UIAUTOMATOR_JAR} exec app_process /system/bin dev.phonedock.Helper ui ${DEVICE_IDLE_EXIT_SEC}`],
      { env: toolEnv(), stdio: ['pipe', 'pipe', 'pipe'] });
    let readyOk!: () => void; let readyFail!: (e: Error) => void;
    this.ready = new Promise((res, rej) => { readyOk = res; readyFail = rej; });
    this.ready.then(() => { this.isReady = true; }, () => undefined);
    const startTimer = setTimeout(() => { readyFail(new Error('helper did not start within 10 s')); void this.close(); }, 10_000);
    this.child.stdout!.on('data', (d: Buffer) => {
      for (const r of this.parser.push(d)) {
        if ('ready' in r) { clearTimeout(startTimer); readyOk(); continue; }
        if ('input' in r) {
          const w = this.inputs.get(r.input.seq); if (!w) continue;
          this.inputs.delete(r.input.seq); clearTimeout(w.timer); w.resolve(r.input);
          continue;
        }
        const p = this.pending.shift(); if (!p) continue;
        clearTimeout(p.timer);
        if (r.ok) p.resolve({ xml: r.xml, idle: r.idle, sinceEventMs: r.sinceEventMs }); else p.reject(new Error(r.error));
      }
    });
    this.child.stderr!.on('data', (d: Buffer) => { if (this.stderr.length < 4000) this.stderr += d.toString(); });
    this.child.stdin!.on('error', () => { /* EPIPE after exit */ });
    this.exited = new Promise((res) => {
      const done = () => {
        clearTimeout(startTimer);
        if (this.idleTimer) clearTimeout(this.idleTimer);
        this.closed = true;
        const err = new Error(`helper exited: ${this.stderr.trim().split('\n').slice(-3).join(' ').slice(0, 400) || 'no output'}`);
        readyFail(err);
        for (const p of this.pending.splice(0)) { clearTimeout(p.timer); p.reject(err); }
        // inputs written but never answered: they may have gone in
        for (const [seq, w] of this.inputs) { clearTimeout(w.timer); w.resolve({ seq, delivery: 'unknown', ms: 0, detail: err.message }); }
        this.inputs.clear();
        res();
      };
      this.child.once('exit', done); this.child.once('error', done);
    });
  }
  private touch() {
    if (this.idleTimer) clearTimeout(this.idleTimer);
    this.idleTimer = setTimeout(() => { if (!this.inputs.size && !this.pending.length) void this.close(); else this.touch(); }, HOST_IDLE_CLOSE_MS);
    this.idleTimer.unref?.();
  }
  dump(quietMs: number, timeoutMs: number, allWindows = false): Promise<DumpResult> {
    if (this.closed) return Promise.reject(new Error('helper closed'));
    this.touch();
    return new Promise((resolve, reject) => {
      const timer = setTimeout(() => { reject(new Error('helper dump timed out')); void this.close(); }, timeoutMs + 5000);
      this.pending.push({ resolve, reject, timer });
      this.child.stdin!.write(`dump ${Math.round(quietMs)} ${Math.round(timeoutMs)}${allWindows ? ' all' : ''}\n`);
    });
  }
  /** Send one input command, exactly once. Resolves with the helper's delivery; a reply that never comes (helper
   *  died, timeout) resolves as 'unknown': the command is never written again. */
  input(cmd: string, timeoutMs: number): Promise<InputReply> {
    if (this.closed) return Promise.resolve({ seq: -1, delivery: 'not_sent', ms: 0, detail: 'helper closed' });
    this.touch();
    const seq = ++this.seq;
    return new Promise((resolve) => {
      const timer = setTimeout(() => {
        this.inputs.delete(seq);
        resolve({ seq, delivery: 'unknown', ms: timeoutMs, detail: 'no reply from the helper in time' });
        void this.close();
      }, timeoutMs);
      this.inputs.set(seq, { resolve, timer });
      this.child.stdin!.write(`in ${seq} ${cmd}\n`);
    });
  }
  /** Close stdin (the helper disconnects UiAutomation and exits), kill after 1.5 s; resolves once it is gone. */
  async close(): Promise<void> {
    if (this.idleTimer) clearTimeout(this.idleTimer);
    if (!this.closed) {
      try { this.child.stdin!.end(); } catch { /* */ }
      const t = setTimeout(() => { try { this.child.kill('SIGKILL'); } catch { /* */ } }, 1500);
      await this.exited;
      clearTimeout(t);
    }
  }
}

const sessions = new Map<string, UiSession>();
const brokenUntil = new Map<string, number>();

/** The running session, starting one when needed. Throws when the helper is unavailable. */
async function session(serial: string): Promise<UiSession> {
  if (!helperEnabled()) throw new Error('helper disabled (PHONEDOCK_ANDROID_HELPER=0)');
  if ((brokenUntil.get(serial) ?? 0) > Date.now()) throw new Error('helper unavailable on this device');
  let s = sessions.get(serial);
  if (!s || s.closed) {
    const dex = await ensureHelper(serial);
    s = sessions.get(serial);                       // a concurrent read may have started it meanwhile
    if (!s || s.closed) { s = new UiSession(serial, dex); sessions.set(serial, s); }
  }
  try {
    await s.ready;
  } catch (e) {
    // Could not start: helper missing (data wiped), no uiautomator.jar, or another UiAutomation client is connected.
    if (sessions.get(serial) === s) sessions.delete(serial);
    forgetInstall(serial);
    brokenUntil.set(serial, Date.now() + 30_000);
    throw e;
  }
  return s;
}

/** Window hierarchy XML through the persistent helper. Throws when the helper is unavailable; the caller then falls
 *  back to `uiautomator dump` (after closeUiHelper: only one UiAutomation connection may exist). */
export async function helperUiDump(serial: string, quietMs = UI_QUIET_MS, timeoutMs = UI_QUIET_TIMEOUT_MS, allWindows = false): Promise<DumpResult> {
  return (await session(serial)).dump(quietMs, timeoutMs, allWindows);
}

/** Inject one input through a session that is already up: `tap x y`, `dtap x y`, `press x y ms`,
 *  `swipe x1 y1 x2 y2 ms holdMs`, `key KEYCODE_…`, `text <base64>`. undefined = no warm session (nothing was sent: the
 *  caller uses `adb shell input`); a session is then started in the background for the next input. The command is
 *  written at most once, whatever happens. */
export async function helperInput(serial: string, cmd: string, timeoutMs = 15_000): Promise<InputReply | undefined> {
  if (!helperInputEnabled() || (brokenUntil.get(serial) ?? 0) > Date.now()) return undefined;
  const s = sessions.get(serial);
  if (!s || s.closed || !s.isReady) { warmHelper(serial); return undefined; }
  return s.input(cmd, timeoutMs);
}
/** Start the session in the background (no-op when it runs, is starting, or is disabled). */
export function warmHelper(serial: string): void {
  if (!helperEnabled() || (brokenUntil.get(serial) ?? 0) > Date.now()) return;
  const s = sessions.get(serial);
  if (s && !s.closed) return;
  session(serial).catch(() => undefined);
}
export async function closeUiHelper(serial: string): Promise<void> {
  const s = sessions.get(serial);
  sessions.delete(serial);
  if (s) await s.close();
}

// ── app labels ──────────────────────────────────────────────────────────────
/** Labels for the given APK paths (one app_process run per 40 APKs). Unknown labels map to ''. */
export async function helperLabels(serial: string, apks: string[], onBatch?: (m: Map<string, string>) => void): Promise<Map<string, string>> {
  const out = new Map<string, string>();
  if (!apks.length) return out;
  if (!helperEnabled()) throw new Error('helper disabled (PHONEDOCK_ANDROID_HELPER=0)');
  const dex = await ensureHelper(serial);
  for (let i = 0; i < apks.length; i += 40) {
    const batch = apks.slice(i, i + 40);
    const r = await adb(serial, ['shell', `CLASSPATH=${dex} app_process /system/bin dev.phonedock.Helper labels ${batch.map(shQuote).join(' ')} 2>/dev/null`],
      { allowFail: true, timeoutMs: 60_000 });
    const got = parseLabelLines(r.stdout);
    if (!got.size) { forgetInstall(serial); throw new Error(`helper labels failed (exit ${r.code}): ${r.stderr.trim().slice(0, 300)}`); }
    for (const [apk, label] of got) out.set(apk, label);
    onBatch?.(got);
  }
  return out;
}
export function parseLabelLines(stdout: string): Map<string, string> {
  const m = new Map<string, string>();
  for (const line of stdout.split('\n')) {
    const t = line.indexOf('\t');
    if (t > 0) m.set(line.slice(0, t), line.slice(t + 1).replace(/\r$/, '').trim());
  }
  return m;
}
